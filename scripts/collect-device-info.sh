#!/usr/bin/env bash
#
# collect-device-info.sh
#
# Read-only inventory of a Steam Deck. Never writes outside the repository,
# never uses sudo, never changes system state.
#
# Output is written to _LLM_WIKI/device/steamdeck-inventory-<date>.md, which is
# gitignored so the collected device state stays local.
#
# Usage:
#   ./scripts/collect-device-info.sh            # default output path
#   OUT=/some/path.md ./scripts/collect-device-info.sh

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATE="$(date +%F)"
OUT="${OUT:-"$REPO_ROOT/_LLM_WIKI/device/steamdeck-inventory-$DATE.md"}"

mkdir -p "$(dirname "$OUT")"

STEAM_DIR="$HOME/.local/share/Steam"
HOMEBREW_DIR="$HOME/homebrew"

section() { printf '\n## %s\n\n' "$1" >> "$OUT"; }
run()    { printf '$ %s\n' "$*" >> "$OUT"; "$@" >> "$OUT" 2>&1 || true; }

{
  echo "# Steam Deck Inventory — $DATE"
  echo
  echo "Generated by \`scripts/collect-device-info.sh\` (read-only)."
  echo "Local/private data; do not commit."
} > "$OUT"

section "System"
run uname -r
grep -E '^(NAME|VERSION|BUILD_ID)=' /etc/os-release >> "$OUT" || true
run gamescope --version

section "Decky Loader"
if [ -d "$HOMEBREW_DIR" ]; then
  cat "$HOMEBREW_DIR/services/.loader.version" >> "$OUT" 2>/dev/null || true
  printf '\nPlugins:\n' >> "$OUT"
  ls -1 "$HOMEBREW_DIR/plugins" >> "$OUT" 2>/dev/null || true
fi
systemctl status plugin_loader.service --no-pager >> "$OUT" 2>&1 || true

section "Flatpak applications"
run flatpak list

section "Graphics mods"
ls -la "$HOME/fgmod" >> "$OUT" 2>&1 || true
ls -la "$HOME/lsfg" >> "$OUT" 2>&1 || true
ls "$HOME/Downloads" >> "$OUT" 2>&1 | grep -iE 'dlss|fsr|frame|opti' || true

section "Steam libraries"
cat "$STEAM_DIR/steamapps/libraryfolders.vdf" >> "$OUT" 2>&1 || true

section "Installed Steam apps"
for lib in "$STEAM_DIR/steamapps" /run/media/deck/*/steamapps; do
  [ -d "$lib" ] || continue
  printf '\nLibrary: %s\n' "$lib" >> "$OUT"
  for f in "$lib"/appmanifest_*.acf; do
    [ -e "$f" ] || continue
    appid="$(grep -m1 '"appid"' "$f" | tr -dc '0-9')"
    name="$(grep -m1 '"name"' "$f" | sed 's/.*"name"[[:space:]]*"\(.*\)"/\1/')"
    printf '%s | %s\n' "$appid" "$name" >> "$OUT"
  done
done

section "Per-game launch options"
python3 - <<'PY' >> "$OUT" 2>&1 || true
import re, glob
for cfg in glob.glob('$STEAM_DIR/userdata/*/config/localconfig.vdf'):
    cur = None
    for ln in open(cfg, encoding='utf-8', errors='replace'):
        m = re.search(r'^\s*"(\d{4,8})"\s*$', ln)
        if m:
            cur = m.group(1)
        m2 = re.search(r'"LaunchOptions"\s+"(.*)"\s*$', ln)
        if m2 and cur:
            print(f"{cur} | {m2.group(1)}")
PY

section "Non-Steam shortcuts"
for f in "$STEAM_DIR"/userdata/*/config/shortcuts.vdf; do
  [ -e "$f" ] || continue
  strings "$f" >> "$OUT" 2>&1 || true
done

echo
echo "Wrote $OUT"
